#!/usr/bin/env python3
"""Merge meta/glossary-staging/*.md into docs/glossary.md (A–Z, deduped).

Staging line format:  - **Term** — one-sentence definition. | NN[, NN]
First definition wins (unless a later one comes from meta/glossary-staging/core.md, which overrides);
chapter references are merged.
"""
from __future__ import annotations

import re
import sys
from collections import OrderedDict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from atlas_lib import DOCS, META, all_chapters  # noqa: E402

LINE_RE = re.compile(r"^\s*-\s+\*\*(.+?)\*\*\s+[—–-]+\s+(.+?)\s*\|\s*([\d., ]+)\s*$")


def norm(term: str) -> str:
    return re.sub(r"[^a-z0-9]", "", term.lower())


def main() -> int:
    chapters = {c["num"]: c for c in all_chapters()}
    terms: "OrderedDict[str, dict]" = OrderedDict()
    staging = sorted((META / "glossary-staging").glob("*.md"))
    core = [p for p in staging if p.stem == "core"]
    rest = [p for p in staging if p.stem != "core"]
    bad = 0
    for p in core + rest:
        for raw in p.read_text().splitlines():
            if not raw.strip() or raw.lstrip().startswith("#"):
                continue
            m = LINE_RE.match(raw)
            if not m:
                bad += 1
                print(f"skip (bad format) {p.name}: {raw[:80]}")
                continue
            term, definition, nums = m.group(1).strip(), m.group(2).strip(), m.group(3)
            key = norm(term)
            refs = [n.strip() for n in nums.split(",") if n.strip()]
            if key not in terms:
                terms[key] = {"term": term, "def": definition, "refs": []}
            for r in refs:
                if r not in terms[key]["refs"] and r in chapters:
                    terms[key]["refs"].append(r)
    items = sorted(terms.values(), key=lambda t: t["term"].lower().lstrip("0123456789/.-"))
    out = ["# Glossary", "",
           f"> {len(items)} terms, A–Z. Each entry is an L1 definition plus links to the chapters that use it. "
           "Generated by `scripts/build_glossary.py` from `meta/glossary-staging/`.", ""]
    letters = sorted({(t["term"].lstrip("0123456789/.-")[:1] or "#").upper() for t in items})
    out.append(" · ".join(f"[{L}](#{L.lower()})" for L in letters if L.isalpha()))
    out.append("")
    current = None
    for t in items:
        L = (t["term"].lstrip("0123456789/.-")[:1] or "#").upper()
        if not L.isalpha():
            L = "#"
        if L != current:
            current = L
            out += ["", f"## {L if L != '#' else 'Numbers and symbols'}", ""]
        refs = []
        for r in sorted(t["refs"], key=lambda x: float(x)):
            ch = chapters[r]
            rel = f"{ch['path'].parent.name}/{ch['path'].name}"
            refs.append(f"[Ch {r}]({rel})")
        ref_txt = f" ({', '.join(refs)})" if refs else ""
        out.append(f"- **{t['term']}** — {t['def']}{ref_txt}")
    (DOCS / "glossary.md").write_text("\n".join(out) + "\n")
    print(f"glossary: {len(items)} terms written; {bad} malformed line(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
