#!/usr/bin/env python3
"""Build meta/sources.md (deduplicated bibliography from every chapter's footnotes + research notes)
and meta/open-questions.md (from meta/open-questions-staging/*.md + inline [VERIFY] markers),
and refresh the tracker table in PROGRESS.md (between <!-- TRACKER --> markers).
"""
from __future__ import annotations

import math
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from atlas_lib import META, ROOT, all_chapters, count_verify, count_visuals, count_words, load_registry  # noqa: E402

URL_RE = re.compile(r"https?://[^\s)>\]]+")


def build_sources() -> int:
    seen: dict[str, dict] = {}
    for ch in all_chapters():
        if not ch["path"].exists():
            continue
        for m in re.finditer(r"^\[\^[^\]]+\]:\s*(.+)$", ch["path"].read_text(), flags=re.M):
            entry = m.group(1).strip()
            urls = URL_RE.findall(entry)
            key = urls[0].rstrip(".,;") if urls else entry.lower()
            if key not in seen:
                seen[key] = {"entry": entry, "chapters": []}
            if ch["num"] not in seen[key]["chapters"]:
                seen[key]["chapters"].append(ch["num"])
    research = sorted((META / "research").glob("*.md"))
    lines = ["# Master bibliography", "",
             f"> {len(seen)} unique sources cited across chapters (deduplicated by URL). Generated by "
             "`scripts/build_meta.py`. Research-sweep notes with additional sources live in `meta/research/`: "
             + ", ".join(f"`{p.name}`" for p in research) + ".", ""]

    def domain(k: str) -> str:
        m = re.match(r"https?://(?:www\.)?([^/]+)", k)
        return m.group(1) if m else "~"

    for key, v in sorted(seen.items(), key=lambda kv: (domain(kv[0]), kv[0])):
        lines.append(f"- {v['entry']} — *cited in Ch {', '.join(v['chapters'])}*")
    (META / "sources.md").write_text("\n".join(lines) + "\n")
    return len(seen)


def build_open_questions() -> tuple[int, int]:
    verify_rows, ask_rows = [], []
    for p in sorted((META / "open-questions-staging").glob("*.md")):
        for raw in p.read_text().splitlines():
            parts = [x.strip() for x in raw.lstrip("- ").split("|")]
            if len(parts) >= 3 and parts[0].upper() == "VERIFY":
                verify_rows.append(parts[1:])
            elif len(parts) >= 4 and parts[0].upper() == "ASK":
                ask_rows.append(parts[1:])
    inline = []
    for ch in all_chapters():
        if ch["path"].exists():
            for m in re.finditer(r"\[VERIFY:?\s*([^\]]*)\]", ch["path"].read_text()):
                inline.append((ch["num"], m.group(1).strip()))
    lines = ["# Open questions", "",
             "Generated by `scripts/build_meta.py`. Two lists: (1) facts that still need verification "
             "(every inline `[VERIFY: …]` marker in the atlas), (2) questions worth asking Everpure people.", "",
             f"## 1. Inline VERIFY markers ({len(inline)})", "", "| Ch | What needs checking |", "|---|---|"]
    lines += [f"| {n} | {t.replace('|', '/')} |" for n, t in inline]
    lines += ["", f"## 2. Logged verification items ({len(verify_rows)})", "",
              "| Ch | Item | Why it matters |", "|---|---|---|"]
    lines += [f"| {r[0]} | {r[1] if len(r) > 1 else ''} | {r[2] if len(r) > 2 else ''} |" for r in verify_rows]
    lines += ["", f"## 3. Questions for Everpure people ({len(ask_rows)})", "",
              "| Ch | Audience | Question |", "|---|---|---|"]
    lines += [f"| {r[0]} | {r[1]} | {r[2]} |" for r in ask_rows]
    rev = META / "review-disagreements.md"
    if rev.exists():
        lines += ["", "## 4. Reviewer disagreements and unresolved findings", "", rev.read_text()]
    (META / "open-questions.md").write_text("\n".join(lines) + "\n")
    return len(inline), len(ask_rows)


def refresh_tracker() -> None:
    prog = ROOT / "PROGRESS.md"
    if not prog.exists():
        return
    rows = ["| Part | Ch | Title | Status | Words / budget | Visuals | VERIFY |", "|---|---|---|---|---|---|---|"]
    tot_w = tot_v = tot_ver = done = 0
    n = 0
    for part in load_registry():
        for ch in part["chapters"]:
            n += 1
            if ch["path"].exists():
                md = ch["path"].read_text()
                w, v, ver = count_words(md), count_visuals(md)["total"], count_verify(md)
                tot_w += w; tot_v += v; tot_ver += ver; done += 1
                status = "✅ drafted"
                rows.append(f"| {part['id']} | {ch['num']} | {ch['title']} | {status} | {w:,} / {ch['budget']:,} | {v} | {ver} |")
            else:
                rows.append(f"| {part['id']} | {ch['num']} | {ch['title']} | ⏳ todo | 0 / {ch['budget']:,} | 0 | 0 |")
    rows.append(f"| | | **Total** | **{done}/{n}** | **{tot_w:,}** | **{tot_v}** | **{tot_ver}** |")
    text = prog.read_text()
    text = re.sub(r"<!-- TRACKER -->.*<!-- /TRACKER -->",
                  "<!-- TRACKER -->\n" + "\n".join(rows) + "\n<!-- /TRACKER -->", text, flags=re.S)
    prog.write_text(text)


def main() -> int:
    (META / "open-questions-staging").mkdir(exist_ok=True)
    s = build_sources()
    v, a = build_open_questions()
    refresh_tracker()
    print(f"sources: {s} unique · inline VERIFY: {v} · questions: {a} · PROGRESS tracker refreshed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
