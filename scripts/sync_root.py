#!/usr/bin/env python3
"""Keep github.com view and MkDocs view in sync.

- docs/glossary.md (canonical)  -> glossary.md (root; links rewritten with docs/ prefix)
- README.md (canonical)         -> docs/index.md (links rewritten: docs/ prefix stripped,
                                    root-only files turned into github.com URLs)
- meta/chapters.yml             -> nav section of mkdocs.yml (between markers)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from atlas_lib import DOCS, ROOT, load_registry  # noqa: E402

REPO_URL = "https://github.com/FrankHuang94/storage-_db_claude/blob/claude/affectionate-gates-srw7gi"
LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def rewrite(text: str, fn) -> str:
    return LINK.sub(lambda m: m.group(1) + fn(m.group(2)) + m.group(3), text)


def to_root(target: str) -> str:
    if re.match(r"^[a-z]+:|^#|^/", target):
        return target
    return "docs/" + target


def to_docs(target: str) -> str:
    if re.match(r"^[a-z]+:|^#|^/", target):
        return target
    if target.startswith("docs/"):
        return target[len("docs/"):]
    return f"{REPO_URL}/{target}"


def write_nav() -> None:
    lines = ["nav:", "  - Home: index.md"]
    for part in load_registry():
        lines.append(f"  - \"{part['title']}\":")
        for ch in part["chapters"]:
            label = f"{ch['num']}. {ch['title']}".replace('"', "'")
            lines.append(f"      - \"{label}\": {part['dir']}/{ch['file']}")
    lines.append("  - Glossary: glossary.md")
    nav = "\n".join(lines)
    mk = ROOT / "mkdocs.yml"
    text = mk.read_text()
    text = re.sub(r"# BEGIN NAV.*# END NAV", f"# BEGIN NAV (generated by scripts/sync_root.py)\n{nav}\n# END NAV",
                  text, flags=re.S)
    mk.write_text(text)


def main() -> int:
    g = DOCS / "glossary.md"
    if g.exists():
        (ROOT / "glossary.md").write_text(
            "<!-- Generated from docs/glossary.md by scripts/sync_root.py — do not edit. -->\n"
            + rewrite(g.read_text(), to_root))
    readme = ROOT / "README.md"
    (DOCS / "index.md").write_text(
        "<!-- Generated from README.md by scripts/sync_root.py — do not edit. -->\n"
        + rewrite(readme.read_text(), to_docs))
    write_nav()
    print("synced glossary.md, docs/index.md, mkdocs nav")
    return 0


if __name__ == "__main__":
    sys.exit(main())
